/// Labels of a document's own date.
const DATE: &[&str] = &["datum", "date", "dated", "ausgestellt am", "vom", "data", "fecha"];

fn words(list: &[(&str, f32)]) -> Vec<Weighted> {
    list.iter().map(|(word, weight)| Weighted { word: (*word).into(), weight: *weight }).collect()
}

fn strings(list: &[&str]) -> Vec<String> {
    list.iter().map(|s| (*s).into()).collect()
}

fn label(labels: &[&str]) -> Find {
    Find::Label { labels: strings(labels) }
}

fn largest(labels: &[&str]) -> Find {
    Find::Largest { labels: strings(labels) }
}

fn sender(markers: &[&[&str]]) -> Find {
    Find::Sender { markers: markers.iter().flat_map(|m| strings(m)).collect() }
}

fn field(key: &str, find: Vec<Find>) -> FieldRules {
    FieldRules { key: key.into(), code: false, find }
}

fn code(key: &str, find: Vec<Find>) -> FieldRules {
    FieldRules { key: key.into(), code: true, find }
}

fn kind(kind: &str, list: &[(&str, f32)], fields: Vec<FieldRules>) -> KindRules {
    KindRules { kind: kind.into(), words: words(list), fields }
}

